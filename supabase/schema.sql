create or replace function public.is_approved_user()
returns boolean
language sql
stable
as $$
  select exists (
    select 1
    from public.user_roles
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

create or replace function public.get_today_queue()
returns table (
  queue_id bigint,
  queue_number integer,
  status text,
  patient_id bigint,
  first_name text,
  last_name text,
  gender text,
  dob date,
  previous_visits bigint,
  visit_id bigint,
  total_bill numeric,
  visit_fee numeric,
  is_paid boolean
)
language sql
stable
as $$
  select
    q.queue_id,
    q.queue_number,
    q.status,
    p.patient_id,
    p.first_name,
    p.last_name,
    p.gender,
    p.dob,
    (
      select count(*)
      from public.visits old_v
      where old_v.patient_id = q.patient_id
        and old_v.visit_date_time::date < current_date
    ) as previous_visits,
    v.visit_id,
    v.total_bill,
    v.visit_fee,
    coalesce(v.is_paid, false) as is_paid
  from public.queue q
  join public.patients p on p.patient_id = q.patient_id
  left join lateral (
    select *
    from public.visits latest_v
    where latest_v.queue_id = q.queue_id
    order by latest_v.visit_id desc
    limit 1
  ) v on true
  where q.queue_date = current_date
  order by
    case q.status when 'waiting' then 1 when 'with_doctor' then 2 else 3 end,
    coalesce(v.is_paid, false),
    q.queue_number;
$$;

