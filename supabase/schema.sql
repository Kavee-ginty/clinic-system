drop policy if exists "approved users read settings" on public.settings;
create policy "approved users read settings" on public.settings for select using (public.is_approved_user());

drop policy if exists "users read own roles" on public.user_roles;
create policy "users read own roles" on public.user_roles for select using (lower(email) = lower(auth.jwt() ->> 'email'));

drop policy if exists "approved users read patients" on public.patients;
create policy "approved users read patients" on public.patients for select using (public.is_approved_user());

drop policy if exists "approved users read queue" on public.queue;
create policy "approved users read queue" on public.queue for select using (public.is_approved_user());

drop policy if exists "approved users read visits" on public.visits;
create policy "approved users read visits" on public.visits for select using (public.is_approved_user());

drop policy if exists "approved users read drugs" on public.drugs;
create policy "approved users read drugs" on public.drugs for select using (public.is_approved_user());

drop policy if exists "approved users read visit drugs" on public.visit_drugs;
create policy "approved users read visit drugs" on public.visit_drugs for select using (public.is_approved_user());

