create table if not exists public.user_roles (
  email text not null,
  role text not null check (role in ('admin', 'doctor', 'receptionist')),
  created_at timestamptz not null default now(),
  primary key (email, role)
);

create table if not exists public.settings (
  setting_key text primary key,
  setting_value text
);

create table if not exists public.patients (
  patient_id bigint generated by default as identity primary key,
  patient_number text default '',
  first_name text not null,
  last_name text not null,
  dob date not null,
  gender text not null default '',
  phone text not null default '',
  address text,
  registered_date date not null default current_date,
  nic text default '',
  age integer default 0
);

create table if not exists public.queue (
  queue_id bigint generated by default as identity primary key,
  patient_id bigint not null references public.patients(patient_id) on delete cascade,
  queue_number integer not null,
  queue_date date not null default current_date,
  status text not null default 'waiting' check (status in ('waiting', 'with_doctor', 'completed')),
  created_at timestamptz not null default now()
);

create table if not exists public.visits (
  visit_id bigint generated by default as identity primary key,
  patient_id bigint not null references public.patients(patient_id) on delete cascade,
  queue_id bigint references public.queue(queue_id) on delete set null,
  visit_date_time timestamptz not null default now(),
  complaint text default '',
  examination text default '',
  investigation text default '',
  diagnosis text default '',
  treatment text default '',
  referals text default '',
  notes text default '',
  visit_fee numeric(10,2) not null default 0,
  total_bill numeric(10,2) not null default 0,
  is_paid boolean not null default false
);

create table if not exists public.drugs (
  drug_id bigint generated by default as identity primary key,
  drug_name text not null,
  dose text default '',
  batch_number text default '',
  quantity integer not null default 0,
  unit_price numeric(10,2) not null default 0
);

create table if not exists public.visit_drugs (
  visit_drug_id bigint generated by default as identity primary key,
  visit_id bigint not null references public.visits(visit_id) on delete cascade,
  drug_id bigint references public.drugs(drug_id) on delete set null,
  drug_name text default '',
  quantity integer not null default 0,
  total_cost numeric(10,2) not null default 0,
  frequency text default '',
  dose text default '',
  duration text default ''
);

create index if not exists patients_last_name_idx on public.patients(last_name);
create index if not exists patients_phone_idx on public.patients(phone);
create index if not exists patients_nic_idx on public.patients(nic);
create index if not exists queue_date_idx on public.queue(queue_date);
create index if not exists queue_status_idx on public.queue(status);
create index if not exists visits_patient_idx on public.visits(patient_id);
create index if not exists visit_drugs_visit_idx on public.visit_drugs(visit_id);

